#!/usr/bin/env bash
# ==============================================================================
# DynamicThemeSync - Synchronizes Hyprland borders and desktop accents
# with the active wallpaper palette extracted by Noctalia.
# ==============================================================================
set -euo pipefail

KITTY_THEME="${XDG_CONFIG_HOME:-$HOME/.config}/kitty/themes/noctalia.conf"
HYPR_DYNAMIC_COLORS="${XDG_CONFIG_HOME:-$HOME/.config}/hypr/config/colors_dynamic.lua"

if [ ! -f "$KITTY_THEME" ]; then
    # Fallback to defaults if noctalia theme does not exist yet
    cat << 'EOF' > "$HYPR_DYNAMIC_COLORS"
-- Fallback dynamic colors
DYNAMIC_ACTIVE_1 = "rgba(01ccffee)"
DYNAMIC_ACTIVE_2 = "rgba(182545ee)"
DYNAMIC_INACTIVE = "rgba(11182688)"
EOF
    exit 0
fi

# Extract hex colors from noctalia.conf
get_color() {
    local key="$1"
    grep -E "^${key}[[:space:]]+" "$KITTY_THEME" | awk '{print $2}' | tr -d '#' | tr '[:upper:]' '[:lower:]' | head -n 1
}

C_ACTIVE=$(get_color "active_border_color")
C_COLOR4=$(get_color "color4")
C_COLOR2=$(get_color "color2")
C_INACTIVE=$(get_color "inactive_border_color")
C_COLOR8=$(get_color "color8")

# Sanity fallbacks
[ -z "$C_ACTIVE" ] && C_ACTIVE="01ccff"
[ -z "$C_COLOR4" ] && C_COLOR4="182545"
[ -z "$C_INACTIVE" ] && C_INACTIVE="111826"

# Write dynamic colors module for Hyprland
cat << EOF > "$HYPR_DYNAMIC_COLORS"
-- Auto-generated by DynamicThemeSync from wallpaper palette
DYNAMIC_ACTIVE_1 = "rgba(${C_ACTIVE}ee)"
DYNAMIC_ACTIVE_2 = "rgba(${C_COLOR4}ee)"
DYNAMIC_INACTIVE = "rgba(${C_INACTIVE}88)"
EOF

# Reload Hyprland to apply border colors
if command -v hyprctl >/dev/null 2>&1; then
    hyprctl reload >/dev/null 2>&1 || true
fi
